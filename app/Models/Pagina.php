<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Carbon;

/**
 * @property array|null $pagina_dados_editor
 * @property string|null $pagina_html_publicado
 * @property string|null $pagina_css_publicado
 * @property string|null $pagina_versao_editor
 * @property Carbon|null $pagina_publicada_em
 * @property int $pagina_versao_rascunho
 * @property int $pagina_versao_publicacao
 * @property string $pagina_estado_editorial
 * @property int|null $revisao_publicada_id
 * @property string|null $pagina_legado_validado_em
 * @property-read PageRevision|null $publishedRevision
 */
class Pagina extends Model
{
    use HasFactory;

    protected $attributes = [
        'pagina_versao_rascunho' => 1,
        'pagina_versao_publicacao' => 0,
        'pagina_estado_editorial' => 'draft',
    ];

    protected $table = 'paginas';

    // Generated by the database; never copy this value into a new page.
    protected $hidden = ['marcador_pagina_inicial'];

    protected $fillable = [
        'pagina_titulo',
        'pagina_tipo_layout',
        'pagina_ativo',
        'grupo_slide',
        'ordem_slide',
        'secao_id',
        'pagina_dados_editor',
        'pagina_html_publicado',
        'pagina_css_publicado',
        'pagina_versao_editor',
        'pagina_publicada_em',
        'pagina_versao_rascunho',
        'pagina_versao_publicacao',
        'pagina_estado_editorial',
        'revisao_publicada_id',
    ];

    protected $casts = [
        'pagina_ativo' => 'boolean',
        'secao_id' => 'integer',
        'pagina_dados_editor' => 'array',
        'pagina_publicada_em' => 'datetime',
        'pagina_versao_rascunho' => 'integer',
        'pagina_versao_publicacao' => 'integer',
    ];

    // Relacionamento 1:N (Uma página possui vários conteúdos)
    public function secao(): BelongsTo
    {
        return $this->belongsTo(Secao::class);
    }

    public function conteudos(): HasMany
    {
        return $this->hasMany(Conteudo::class, 'pagina_id')->orderBy('conteudo_ordem_exibicao', 'asc');
    }

    public function revisions(): HasMany
    {
        return $this->hasMany(PageRevision::class)->orderByDesc('versao');
    }

    public function publishedRevision(): BelongsTo
    {
        return $this->belongsTo(PageRevision::class, 'revisao_publicada_id');
    }

    public function reviewRequests(): HasMany
    {
        return $this->hasMany(ReviewRequest::class);
    }

    public function mediaAssets(): BelongsToMany
    {
        return $this->belongsToMany(MediaAsset::class, 'referencias_midia', 'pagina_id', 'midia_id')->withTimestamps();
    }
}
